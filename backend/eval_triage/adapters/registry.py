def get_adapter(name: str):
    if name == "demo":
        from eval_triage.adapters.demo import DemoAdapter

        return DemoAdapter()
    if name == "openai":
        from eval_triage.adapters.openai_adapter import OpenAIAdapter

        return OpenAIAdapter()
    if name == "anthropic":
        from eval_triage.adapters.anthropic_adapter import AnthropicAdapter

        return AnthropicAdapter()
    if name == "openai_compatible":
        from eval_triage.adapters.local_adapter import LocalOpenAICompatibleAdapter

        return LocalOpenAICompatibleAdapter()
    if name == "memoryai":
        from eval_triage.adapters.memoryai.adapter import MemoryAIAdapter

        return MemoryAIAdapter()
    raise KeyError(f"unknown adapter {name!r}")


def adapter_version(name: str) -> str:
    return getattr(get_adapter(name), "version", "unknown")
